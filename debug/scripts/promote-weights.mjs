#!/usr/bin/env node
/**
 * Přenos natrénovaných vah do debug AI (debug/js/ai-tactical-weights.js).
 *
 * Bez --approve skript jen změří a vypíše výsledek, nic nezapisuje.
 * Se --approve zapíše váhy jen tehdy, když šampion v NOVÉ nezávislé sérii partií
 * statisticky významně poráží původní váhy (z > 1,645). Přenos do produkční hry
 * je samostatný krok, který se neprovádí automaticky.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { evaluateMatch, toObject, clampVector, ALL_SETUPS, KEYS as keys, DEFAULT_WEIGHTS as defaults } from './train-selfplay.mjs';
import { AI_WEIGHT_DEFINITIONS } from '../js/ai-weight-config.js';

const argv = process.argv.slice(2);
const read = (name, fallback) => {
    const item = argv.find(value => value.startsWith('--' + name + '='));
    return item ? item.slice(name.length + 3) : fallback;
};
const checkpointPath = resolve(read('checkpoint', 'artifacts/selfplay-checkpoint.json'));
const configDir = resolve(read('config-dir', 'debug/config'));
const jsPath = resolve(read('js-file', 'debug/js/ai-tactical-weights.js'));
const games = Math.max(100, Number(read('games', 600)));
const approve = argv.includes('--approve');
const bigGames = Math.max(0, Number(read('big-games', 0)));

const basicKeys = new Set(AI_WEIGHT_DEFINITIONS.map(item => item.key));

const state = JSON.parse(await readFile(checkpointPath, 'utf8'));
if (state.format !== 'clovece-selfplay-checkpoint' || state.version !== 2 || !Array.isArray(state.champion) ||
    state.champion.length !== keys.length) {
    throw new Error('Checkpoint nemá platný formát.');
}
const champion = clampVector(state.champion.map(Number));
const setups = [{ playerCount: 2, boardSize: 40 }, { playerCount: 4, boardSize: 40 }];

const result = evaluateMatch({
    candidate: champion,
    opponent: { type: 'weights', weights: defaults, temperature: 0 },
    setups, games, seedBase: 31000000, maxTurns: 1500
});
const passed = result.decisive >= games * 0.8 && result.z > 1.645;

process.stdout.write('Šampion vs původní váhy: ' + result.wins + '/' + result.decisive +
    ' výher (' + (result.winRate * 100).toFixed(1) + ' %, náhodná šance ' + (result.chanceRate * 100).toFixed(1) +
    ' %), z = ' + result.z.toFixed(2) + (passed ? ' → PROŠEL' : ' → NEPROŠEL') + '\n');
for (const key of keys) {
    const before = defaults[keys.indexOf(key)];
    const after = champion[keys.indexOf(key)];
    process.stdout.write('  ' + key.padEnd(18) + String(before).padStart(8) + ' → ' + after.toFixed(3) + '\n');
}

if (bigGames > 0) {
    // Orientační kontrola na deskách 48 a 80 polí. Partie nedoběhnou, vítěz = vedoucí podle zbývajících kroků.
    // Nepočítá se do podmínky nasazení.
    const large = evaluateMatch({
        candidate: champion, opponent: { type: 'weights', weights: defaults, temperature: 0 },
        setups: ALL_SETUPS.filter(item => item.large), games: bigGames, seedBase: 32000000, maxTurns: 1500, useSurrogate: true
    });
    process.stdout.write('Velké desky (48 a 80 polí, ORIENTAČNĚ, ' + large.surrogate + '/' + large.decisive +
        ' partií rozhodnuto podle vedoucího při limitu): ' + large.wins + '/' + large.decisive + ' výher (' +
        (large.winRate * 100).toFixed(1) + ' %, náhodná šance ' + (large.chanceRate * 100).toFixed(1) + ' %), z = ' + large.z.toFixed(2) + '\n');
}

if (!approve) {
    process.stdout.write('Bez --approve nebylo nic zapsáno.\n');
} else if (!passed) {
    process.stdout.write('Váhy nebyly zapsány: nejsou prokazatelně lepší než původní.\n');
    process.exitCode = 2;
} else {
    const all = toObject(champion.map(value => Number(value.toFixed(4))));
    const weights = Object.fromEntries(Object.entries(all).filter(([key]) => basicKeys.has(key)));
    const extended = Object.fromEntries(Object.entries(all).filter(([key]) => !basicKeys.has(key)));
    await mkdir(configDir, { recursive: true });
    await writeFile(resolve(configDir, 'ai-tactical-weights.json'), JSON.stringify({
        version: 4, trainedAt: new Date().toISOString(),
        trainingMethod: 'selfplay-cem-or-reinforce', sourceGames: state.gamesPlayed,
        validation: { games: result.decisive, wins: result.wins, winRate: result.winRate, z: result.z },
        weights, extendedWeights: extended
    }, null, 2) + '\n');
    await mkdir(dirname(jsPath), { recursive: true });
    const header = '// Generated by debug/scripts/promote-weights.mjs. Do not edit manually.\n';
    await writeFile(jsPath, '// /debug/js/ai-tactical-weights.js\n' + header +
        'export const AI_TACTICAL_WEIGHTS = Object.freeze(' + JSON.stringify(weights, null, 2) + ');\n');
    await writeFile(resolve(dirname(jsPath), 'ai-extended-tactical-weights.js'),
        '// /debug/js/ai-extended-tactical-weights.js\n' + header +
        'export const AI_EXTENDED_TACTICAL_WEIGHTS = Object.freeze(' + JSON.stringify(extended, null, 2) + ');\n');
    await writeFile(resolve(configDir, 'ai-training-state.json'), JSON.stringify({
        format: 'clovece-ai-training-state', version: 3, updatedAt: new Date().toISOString(),
        status: 'trained-validated', statusLabel: '18 STRATEGICKÝCH VAH NATRÉNOVÁNO A OVĚŘENO',
        previousWeights: toObject(defaults), finalWeights: all,
        training: { method: 'REINFORCE + Adam, self-play proti šampionovi', source: { completedGames: state.gamesPlayed },
            validation: { games: result.decisive, wins: result.wins, winRate: result.winRate, z: result.z } }
    }, null, 2) + '\n');
    process.stdout.write('Zapsáno: ' + jsPath + ', ai-extended-tactical-weights.js a ' + configDir + '\n');
}
